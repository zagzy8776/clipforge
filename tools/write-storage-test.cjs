var fs = require("fs");
var L = [];
L.push('import { describe, it, expect } from "vitest";');
L.push('import { MemoryRepository, runPipeline } from "../packages/storage/src/index";');
L.push('');
L.push('function tp(id="p1") { return { id, name:"Test", sourcePath:"/t.mp4", status:"created" as const, segments:[], sections:[], candidates:[], clips:[], stats:{totalCandidates:0,selectedClips:0,validatedClips:0,avgEngagement:0,avgQuality:0,totalRenderTimeMs:0,totalSizeMB:0}, createdAt:new Date().toISOString(), updatedAt:new Date().toISOString() }; }');
L.push('function tc(id="c1",pid="p1") { return { id, index:0, projectId:pid, sourceStart:0, sourceEnd:30, directorPlan:{hook:"t",pacing:"natural" as const,visualStyle:"clean" as const,musicStrategy:"none" as const,captionStrategy:"standard" as const,framingStrategy:"center" as const,effects:[],transitions:[],emphasisMoments:[],reasoning:"t",confidence:70}, profileName:"podcast", artifacts:{}, status:"rendered" as const, score:50 }; }');
L.push('');
L.push('describe("MemoryRepository", () => {');
L.push('  const repo = new MemoryRepository();');
L.push('  it("CRUD projects", async () => {');
L.push('    const p = tp(); await repo.createProject(p);');
L.push('    expect(await repo.getProject(p.id)).toEqual(p);');
L.push('    await repo.updateProject(p.id, { name: "Updated" });');
L.push('    expect((await repo.getProject(p.id))!.name).toBe("Updated");');
L.push('    await repo.deleteProject(p.id);');
L.push('    expect(await repo.getProject(p.id)).toBeNull();');
L.push('  });');
L.push('  it("CRUD clips", async () => {');
L.push('    const c = tc(); await repo.createClip(c);');
L.push('    expect(await repo.getClip(c.id)).toEqual(c);');
L.push('    await repo.updateClip(c.id, { score: 90 });');
L.push('    expect((await repo.getClip(c.id))!.score).toBe(90);');
L.push('    await repo.deleteClip(c.id);');
L.push('  });');
L.push('  it("CRUD jobs + cancel", async () => {');
L.push('    const job = await repo.createJob({ projectId:"p1", type:"render", status:"queued", progress:0, message:"q", input:{}, artifacts:[], retries:0, maxRetries:2 });');
L.push('    expect(await repo.getJob(job.id)).not.toBeNull();');
L.push('    await repo.updateJob(job.id, { progress: 50 });');
L.push('    expect((await repo.getJob(job.id))!.progress).toBe(50);');
L.push('    await repo.cancelJob(job.id);');
L.push('    expect((await repo.getJob(job.id))!.status).toBe("cancelled");');
L.push('  });');
L.push('  it("cascade delete", async () => {');
L.push('    await repo.createProject(tp("px")); await repo.createClip(tc("cx","px"));');
L.push('    await repo.createJob({ projectId:"px", type:"render", status:"running", progress:50, message:"t", input:{}, artifacts:[], retries:0, maxRetries:2 });');
L.push('    await repo.deleteProject("px");');
L.push('    expect((await repo.getClips("px")).length).toBe(0);');
L.push('  });');
L.push('});');
L.push('');
L.push('describe("Job Runner", () => {');
L.push('  it("runs full pipeline", async () => {');
L.push('    const repo = new MemoryRepository(); await repo.createProject(tp("pp"));');
L.push('    const stages: string[] = [];');
L.push('    const r = await runPipeline("pp", repo, {');
L.push('      ingest: async (_j,up) => { await up(50,"ing"); stages.push("ing"); return {_artifacts:["v.mp4"]}; },');
L.push('      transcribe: async (_j,up) => { await up(50,"tr"); stages.push("tr"); return {_artifacts:["t.json"]}; },');
L.push('      analyze: async (_j,up) => { await up(50,"an"); stages.push("an"); return {_artifacts:["a.json"]}; },');
L.push('      direct: async (_j,up) => { await up(50,"di"); stages.push("di"); return {_artifacts:["d.json"]}; },');
L.push('      render: async (_j,up) => { await up(50,"re"); stages.push("re"); return {_artifacts:["c.mp4"]}; },');
L.push('      validate: async (_j,up) => { await up(100,"va"); stages.push("va"); return {_artifacts:[]}; },');
L.push('    });');
L.push('    expect(r.success).toBe(true);');
L.push('    expect(stages).toEqual(["ing","tr","an","di","re","va"]);');
L.push('  });');
L.push('  it("stops on failure", async () => {');
L.push('    const repo = new MemoryRepository(); await repo.createProject(pf("pf"));');
L.push('    const stages: string[] = [];');
L.push('    const r = await runPipeline("pf", repo, {');
L.push('      ingest: async () => { stages.push("ing"); return {_artifacts:[]}; },');
L.push('      transcribe: async () => { throw new Error("fail"); },');
L.push('      analyze: async () => { stages.push("an"); return {_artifacts:[]}; },');
L.push('    });');
L.push('    expect(r.success).toBe(false);');
L.push('    expect(stages).toEqual(["ing"]);');
L.push('  });');
L.push('  it("retries transient failures", async () => {');
L.push('    const repo = new MemoryRepository(); await repo.createProject(tp("pr"));');
L.push('    let n = 0;');
L.push('    const r = await runPipeline("pr", repo, {');
L.push('      render: async () => { n++; if(n<2) throw new Error("temp"); return {_artifacts:["c.mp4"]}; },');
L.push('    });');
L.push('    expect(r.success).toBe(true);');
L.push('    expect(n).toBe(2);');
L.push('  });');
L.push('});');
fs.writeFileSync("e:/video/tests/storage.test.ts", L.join("\n") + "\n", "utf-8");
console.log("Wrote storage.test.ts:", L.length, "lines");
